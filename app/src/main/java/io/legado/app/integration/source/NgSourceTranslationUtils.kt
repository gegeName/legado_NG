package io.legado.app.integration.source

internal fun translateToChinese(text: String): String {
    if (text.isBlank()) return text
    val trimmed = text.trim()

    val directMatch = translationMap[trimmed]
        ?: translationMap[trimmed.lowercase()]
        ?: translationMap[trimmed.lowercase().replaceFirstChar { it.uppercase() }]
    if (directMatch != null) return directMatch

    var phraseResult = trimmed
    phraseReplacements.forEach { (english, chinese) ->
        if (phraseResult.contains(english, ignoreCase = true)) {
            phraseResult = phraseResult.replace(Regex("(?i)\\b" + Regex.escape(english) + "\\b"), chinese)
        }
    }
    if (phraseResult != trimmed) return phraseResult

    if (trimmed.all { it.isLetter() || it.isWhitespace() || it == '-' || it == '_' }) {
        val words = trimmed.split(Regex("[\\s-_]+"))
        val translatedWords = words.map { word ->
            translationMap[word]
                ?: translationMap[word.lowercase()]
                ?: translationMap[word.lowercase().replaceFirstChar { it.uppercase() }]
                ?: word
        }
        if (translatedWords != words) {
            return translatedWords.joinToString("")
        }
    }

    return text
}

